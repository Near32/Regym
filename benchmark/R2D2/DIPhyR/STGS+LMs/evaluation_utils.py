"""
Utilities for evaluating generated outputs against targets.
"""
from collections import defaultdict
from metrics_utils import (
    compute_bertscore,
    compute_mauve_score,
)
import logging

logger = logging.getLogger("evaluation_utils")


def evaluate_generated_output(generated_tokens, target_tokens, tokenizer, device=None):
    """
    Evaluate the generated output against the target.
    
    Args:
        generated_tokens: Tokens generated by the optimized prompt
        target_tokens: Target tokens to match
        tokenizer: Tokenizer for decoding
        device: Device to run on (default: None, will use GPU if available)
        
    Returns:
        metrics: Dictionary containing evaluation metrics
    """
    metrics = {}
    
    # Compare sequence lengths
    gen_len = len(generated_tokens)
    target_len = len(target_tokens)
    
    # Calculate exact match (boolean)
    is_exact_match = (generated_tokens == target_tokens)
    metrics["exact_match"] = int(is_exact_match)
    
    # Calculate token-level accuracy
    min_len = min(gen_len, target_len)
    if min_len > 0:
        matching_tokens = sum(generated_tokens[i] == target_tokens[i] for i in range(min_len))
        metrics["token_accuracy"] = matching_tokens / target_len
    else:
        metrics["token_accuracy"] = 0.0
    
    # Calculate BLEU-like n-gram overlap (simplified for n=1,2)
    metrics["unigram_overlap"] = calculate_ngram_overlap(generated_tokens, target_tokens, n=1)
    metrics["bigram_overlap"] = calculate_ngram_overlap(generated_tokens, target_tokens, n=2)
    
    # Calculate longest common subsequence ratio
    if target_len > 0:
        lcs = lcs_length(generated_tokens, target_tokens)
        metrics["lcs_ratio"] = lcs / target_len
    else:
        metrics["lcs_ratio"] = 0.0
    
    # Decode tokens for visual comparison
    generated_text = tokenizer.decode(generated_tokens)
    target_text = tokenizer.decode(target_tokens)
    metrics["generated_text"] = generated_text
    metrics["target_text"] = target_text
    
    # Compute BERTScore
    bertscore_results = compute_bertscore([generated_text], [target_text], device=device)
    metrics["bertscore_precision"] = bertscore_results["precision"]
    metrics["bertscore_recall"] = bertscore_results["recall"]
    metrics["bertscore_f1"] = bertscore_results["f1"]
    
    # Compute MAUVE score if both texts are long enough
    if len(generated_text.split()) > 2 and len(target_text.split()) > 2:
        try:
            mauve_score = compute_mauve_score([generated_text], [target_text], device=device)
            metrics["mauve_score"] = mauve_score
        except Exception as e:
            logger.warning(f"Could not compute MAUVE score: {e}")
            metrics["mauve_score"] = 0.0
    else:
        metrics["mauve_score"] = 0.0
   
    return metrics


def calculate_ngram_overlap(generated_tokens, target_tokens, n=1):
    """
    Calculate the n-gram overlap between generated and target tokens.
    
    Args:
        generated_tokens: List of generated token IDs
        target_tokens: List of target token IDs
        n: Size of n-grams to compare
        
    Returns:
        float: Ratio of matching n-grams to total target n-grams
    """
    if len(generated_tokens) < n or len(target_tokens) < n:
        return 0.0
        
    gen_ngrams = [tuple(generated_tokens[i:i+n]) for i in range(len(generated_tokens)-n+1)]
    target_ngrams = [tuple(target_tokens[i:i+n]) for i in range(len(target_tokens)-n+1)]
    
    gen_counter = defaultdict(int)
    target_counter = defaultdict(int)
    
    for ngram in gen_ngrams:
        gen_counter[ngram] += 1
    
    for ngram in target_ngrams:
        target_counter[ngram] += 1
    
    matches = 0
    for ngram, count in gen_counter.items():
        matches += min(count, target_counter[ngram])
        
    return matches / len(target_ngrams) if target_ngrams else 0.0


def lcs_length(a, b):
    """
    Calculate the length of the longest common subsequence between two sequences.
    
    Args:
        a: First sequence
        b: Second sequence
        
    Returns:
        int: Length of the longest common subsequence
    """
    m, n = len(a), len(b)
    dp = [[0] * (n + 1) for _ in range(m + 1)]
    
    for i in range(1, m + 1):
        for j in range(1, n + 1):
            if a[i-1] == b[j-1]:
                dp[i][j] = dp[i-1][j-1] + 1
            else:
                dp[i][j] = max(dp[i-1][j], dp[i][j-1])
                
    return dp[m][n]
